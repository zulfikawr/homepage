export type IconName = keyof typeof iconMap | keyof typeof iconifyMap;

interface IconProps extends Omit<
  React.SVGProps<SVGSVGElement>,
  'name' | 'size' | 'mode' | 'onLoad' | 'rotate'
> {
  name: IconName;
  className?: string;
  size?: number | string;
  color?: string;
  weight?: 'thin' | 'light' | 'regular' | 'bold' | 'fill' | 'duotone';
  mirrored?: boolean;
  rotate?: number;
}

const Icon = ({ name, className, size = 20, ...props }: IconProps) => {
  if (name in iconifyMap) {
    return (
      <TechIcon
        name={name}
        size={size}
        className={className}
        style={props.style}
      />
    );
  }

  const IconComponent = iconMap[name as keyof typeof iconMap];

  if (!IconComponent) {
    console.warn(`Icon with name "${name}" not found`);
    return null;
  }

  return (
    <IconComponent
      className={className}
      size={size}
      {...(props as Parameters<typeof IconComponent>[0])}
    />
  );
};

Icon.displayName = 'Icon';

export { Icon };
